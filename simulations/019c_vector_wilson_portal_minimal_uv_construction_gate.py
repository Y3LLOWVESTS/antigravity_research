def bridge_upper_bound(a019, N: int, rho: float, margin: float) -> BridgeBoundPoint | None:
    """Optimistic perturbative upper bound for the minimal loop-seeded bridge."""
    try:
        mu, f, theta, kappa = minimal_mu_for_wilson(a019, N, rho, margin)
    except ValueError:
        return None

    s2 = abs(cw_second_earth_mp(a019, N, rho, theta))

    # Saturate every scale and coupling in the favorable direction.
    vector_mass = margin * MATERIAL_EFT_CUTOFF
    v = vector_mass / (math.sqrt(2.0) * G_MAX)
    p_mass = margin * MATERIAL_EFT_CUTOFF

    # Require the radial bridge-Higgs mode sqrt(2 lambda) v itself to be above
    # the same margin*cutoff.  At v_min this saturates lambda=4 pi.
    lambda_s = (margin * MATERIAL_EFT_CUTOFF) ** 2 / (2.0 * v * v)

    # kappa_P/m_P <= sqrt(4pi) and y_P <= sqrt(4pi), so their product <=4pi.
    # C <= mu^3 |S''| / [32 pi m_P lambda f v^4].
    c_upper = mu**3 * s2 / (
        32.0 * math.pi * p_mass * lambda_s * f * v**4
    )

    return BridgeBoundPoint(
        N=N,
        rho=rho,
        margin=margin,
        mu=mu,
        f=f,
        theta=theta,
        kappa_cw=kappa,
        cw_second_earth=s2,
        vector_mass=vector_mass,
        bridge_vev=v,
        p_mass=p_mass,
        lambda_s=lambda_s,
        c_upper=c_upper,
        fraction_of_target=c_upper / TARGET_C_PHI,
    )


