def exact_scalar(path: Path, label: str) -> float:
    """Read one floating scalar from an exact whole-line label."""
    text = path.read_text(errors="replace")
    pattern = (
        r"(?m)^" + re.escape(label) +
        r"([+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)\s*$"
    )
    match = re.search(pattern, text)
    if match is None:
        raise RuntimeError(f"Missing exact scalar line {label!r} in {path}")
    value = float(match.group(1))
    if not math.isfinite(value):
        raise RuntimeError(f"Nonfinite {label!r}")
    return value


def relative_error(a: float, b: float) -> float:
    return abs(a - b) / max(abs(a), abs(b), 1.0e-300)


def pair_radius_evinv() -> float:
    """Convert the inherited 3 Angstrom pair radius to eV^-1."""
    radius_nm = PAIR_RADIUS_ANGSTROM * 0.1
    return radius_nm / HBARC_EV_NM


def psi0_sq() -> float:
    a = pair_radius_evinv()
    return 1.0 / (math.pi * a**3)


def equal_mass_pair_kernel_analytic(M: float) -> float:
    """Exact <q^2/(q^2+M^2)^2> kernel in the normalized 1s density."""
    a = pair_radius_evinv()
    k = M + 2.0 / a
    return psi0_sq() * (2.0 / a) / (k**3)


def equal_mass_pair_kernel_numeric(M: float) -> float:
    """Independent coordinate-space quadrature of the same kernel."""
    a = pair_radius_evinv()
    norm = psi0_sq()

    # Fourier transform:
    # q^2/(q^2+M^2)^2 = 1/(q^2+M^2) - M^2/(q^2+M^2)^2
    # K(r) = exp(-Mr)/(4 pi r) - M exp(-Mr)/(8 pi).
    def integrand(r: float) -> float:
        density = norm * math.exp(-2.0 * r / a)
        kernel = math.exp(-M * r) * (1.0 / (4.0 * math.pi * r) - M / (8.0 * math.pi))
        return 4.0 * math.pi * r * r * density * kernel

    # Remove the removable r=0 numerical singularity by starting at a tiny
    # positive radius.  Its omitted contribution is negligible at this scale.
    value, _ = quad(integrand, 1.0e-14 * a, 100.0 * a, epsabs=1.0e-12, epsrel=2.0e-11, limit=400)
    return value


def dlogdet_matrix(a019, N: int, rho: float, theta: float) -> float:
    """Return a double-precision Tr[L^-1 L'] diagnostic."""
    L = a019.lattice_matrix(N, rho, theta)
    Lp = a019.lattice_matrix_prime(N, rho, theta)
    return float(np.real(np.trace(np.linalg.solve(L, Lp))))


def dlogdet_matrix_mp(N: int, rho: float, theta: float) -> mp.mpf:
    """High-precision matrix reconstruction of Tr[L^-1 L']."""
    rho_mp = mp.mpf(str(rho))
    theta_mp = mp.mpf(str(theta))
    link = mp.e ** (1j * theta_mp / N)

    L = mp.matrix(N)
    Lp = mp.matrix(N)
    for i in range(N):
        for j in range(N):
            L[i, j] = 0
            Lp[i, j] = 0
        L[i, i] = rho_mp * rho_mp + 2

    for j in range(N):
        k = (j + 1) % N
        L[j, k] += -link
        L[k, j] += -mp.conj(link)
        Lp[j, k] += -(1j / N) * link
        Lp[k, j] += +(1j / N) * mp.conj(link)

    G = L ** -1
    product = G * Lp
    return mp.re(sum(product[i, i] for i in range(N)))


def dlogdet_spectral_mp(N: int, rho: float, theta: float) -> mp.mpf:
    """High-precision spectral reconstruction of d log det L/dtheta."""
    rho_mp = mp.mpf(str(rho))
    theta_mp = mp.mpf(str(theta))
    total = mp.mpf('0')
    for n in range(N):
        angle = (2 * mp.pi * n + theta_mp) / N
        lam = rho_mp * rho_mp + 2 - 2 * mp.cos(angle)
        lp = (mp.mpf(2) / N) * mp.sin(angle)
        total += lp / lam
    return total


def dlogdet_closed_mp(N: int, rho: float, theta: float) -> mp.mpf:
    """High-precision closed determinant identity."""
    rho_mp = mp.mpf(str(rho))
    theta_mp = mp.mpf(str(theta))
    alpha = mp.acosh(1 + rho_mp * rho_mp / 2)
    return mp.sin(theta_mp) / (mp.cosh(N * alpha) - mp.cos(theta_mp))


def dlogdet_spectral(N: int, rho: float, theta: float) -> float:
    """Independent Fourier-spectrum d log det L/dtheta."""
    total = 0.0
    for n in range(N):
        angle = (2.0 * math.pi * n + theta) / N
        lam = rho * rho + 2.0 - 2.0 * math.cos(angle)
        lp = (2.0 / N) * math.sin(angle)
        total += lp / lam
    return total


def dlogdet_closed(N: int, rho: float, theta: float) -> float:
    """Closed determinant identity for a third independent check."""
    alpha = math.acosh(1.0 + 0.5 * rho * rho)
    return math.sin(theta) / (math.cosh(N * alpha) - math.cos(theta))


def minimal_mu_for_wilson(a019, N: int, rho: float, margin: float) -> tuple[float, float, float, float]:
    """Return minimal mu, f, theta_E and positive CW kappa under gate constraints."""
    kappa = float(a019.cw_curvature_analytic_mp(N, rho))
    if not (math.isfinite(kappa) and kappa > 0.0):
        raise ValueError("nonpositive CW curvature")

    # f = mu^2 sqrt(kappa)/(8 pi m_phi).
    f_min_earth = EARTH_PHI / MAX_THETA_EARTH
    mu_for_earth = math.sqrt(
        f_min_earth * 8.0 * math.pi * TARGET_M_PHI / math.sqrt(kappa)
    )
    mu_for_messenger = margin * MATERIAL_EFT_CUTOFF / rho
    mu = max(mu_for_earth, mu_for_messenger)
    f = mu * mu * math.sqrt(kappa) / (8.0 * math.pi * TARGET_M_PHI)
    theta = EARTH_PHI / f
    return mu, f, theta, kappa


def kinetic_point(a019, N: int, rho: float, margin: float) -> KineticPoint | None:
    """Compute the most optimistic equal-coupling kinetic portal point."""
    try:
        mu, f, theta, kappa = minimal_mu_for_wilson(a019, N, rho, margin)
    except ValueError:
        return None

    dlog = abs(dlogdet_spectral(N, rho, theta))
    if dlog <= 0.0:
        return None

    vector_mass = margin * MATERIAL_EFT_CUTOFF
    kernel = equal_mass_pair_kernel_analytic(vector_mass)
    target_pair_charge = TARGET_C_PHI * psi0_sq()

    # q_target = g^4 dlog K /(12 pi^2 f) for g_B=g_L=g.
    g4 = target_pair_charge * 12.0 * math.pi**2 * f / (dlog * kernel)
    if g4 <= 0.0:
        return None
    g = g4**0.25
    alpha = g * g / (4.0 * math.pi)

    return KineticPoint(
        N=N,
        rho=rho,
        margin=margin,
        mu=mu,
        f=f,
        theta=theta,
        kappa=kappa,
        dlogdet=dlog,
        vector_mass=vector_mass,
        pair_kernel=kernel,
        g_endpoint=g,
        alpha_endpoint=alpha,
        messenger_margin=mu * rho / MATERIAL_EFT_CUTOFF,
    )


def bridge_exact_coefficient(eta: float, theta: float, f: float, v: float) -> float:
    """Exact dK_BL/dphi for d(theta)=eta sin(theta)."""
    d = eta * math.sin(theta)
    dp = eta * math.cos(theta)
    if abs(d) >= 1.0:
        return math.inf
    return dp * (1.0 + d * d) / (2.0 * f * v * v * (1.0 - d * d) ** 2)


def solve_bridge_eta(theta: float, f: float, v: float) -> float:
    """Solve the exact Higgs-bridge algebra for eta."""
    upper = min(4.0, 0.999999 / max(abs(math.sin(theta)), 1.0e-30))
    func = lambda eta: bridge_exact_coefficient(eta, theta, f, v) - TARGET_C_PHI
    if func(upper) < 0.0:
        raise RuntimeError("Bridge algebra cannot reach target within positive-VEV domain")
    return brentq(func, 1.0e-15, upper, xtol=1.0e-14, rtol=1.0e-13)


