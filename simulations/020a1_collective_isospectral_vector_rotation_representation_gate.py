def pauli_matrices() -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return sigma_x, sigma_y, sigma_z."""

    sx = np.array([[0.0, 1.0], [1.0, 0.0]], dtype=complex)
    sy = np.array([[0.0, -1.0j], [1.0j, 0.0]], dtype=complex)
    sz = np.array([[1.0, 0.0], [0.0, -1.0]], dtype=complex)
    return sx, sy, sz


def su2_adjoint_matrix(phi: np.ndarray) -> np.ndarray:
    """Return Phi = phi^a sigma^a / 2 in the fundamental representation."""

    sx, sy, sz = pauli_matrices()
    return 0.5 * (phi[0] * sx + phi[1] * sy + phi[2] * sz)


def su2_vector_mass2(
    beta: float,
    g_x: float,
    u: float,
    v: float,
) -> np.ndarray:
    """Return SU(2) vector mass-squared from one fundamental + one adjoint."""

    n = np.array([math.sin(beta), 0.0, math.cos(beta)], dtype=float)
    m0_sq = g_x * g_x * u * u / 4.0
    adj_sq = g_x * g_x * v * v
    return m0_sq * np.eye(3) + adj_sq * (np.eye(3) - np.outer(n, n))


