def finite_difference_cross_derivative(
    theta: float,
    kappa: float,
    m1: float,
    m2: float,
    step: float = 1.0e-5,
) -> float:
    """Independently reconstruct d[M^-2]_BL/dtheta by matrix inversion."""

    def cross(t: float) -> float:
        inv = np.linalg.inv(isospectral_mass2(t, kappa, m1, m2))
        return float(inv[0, 1])

    return (cross(theta + step) - cross(theta - step)) / (2.0 * step)


