def solve_exact_allowed_epsilon(
    a2,
    point: dict[str, float],
    selected_f: float,
) -> float:
    """Solve high-precision |delta m_phi^2|/m_phi^2 = 1."""

    def residual(log10_epsilon: float) -> float:
        epsilon = 10.0**log10_epsilon
        ratio = high_precision_ratio(
            a2,
            epsilon,
            point,
            selected_f,
        )
        return ratio - 1.0

    lo = math.log10(EPS_ROOT_MIN)
    hi = math.log10(EPS_ROOT_MAX)

    f_lo = residual(lo)
    f_hi = residual(hi)

    if f_lo > 0.0:
        # Allowed value lies below our already extremely small bracket.
        return EPS_ROOT_MIN

    if f_hi < 0.0:
        # This would mean the point is far more natural than anticipated.
        # Enlarge conservatively but remain inside the small-breaking regime.
        hi2 = math.log10(0.05)
        f_hi2 = residual(hi2)
        if f_hi2 < 0.0:
            return 0.05
        hi = hi2

    root = brentq(
        residual,
        lo,
        hi,
        xtol=1.0e-10,
        rtol=1.0e-10,
        maxiter=100,
    )

    return 10.0**root


def reconstruct_global_grid(
    a2,
    selected_f: float,
    theta_earth: float,
) -> list[dict[str, float]]:
    """Reconstruct every target-matching point in the original 020A2 grid."""

    candidates: list[dict[str, float]] = []

    for g_x_raw in a2.GX_GRID:
        for g_raw in a2.G_GRID:
            g_x = float(g_x_raw)
            g = float(g_raw)

            if (
                g_x > a2.PERTURBATIVE_G_MAX
                or g > a2.PERTURBATIVE_G_MAX
            ):
                continue

            for r_raw in a2.R_GRID:
                r = float(r_raw)

                u = a2.scale_u_to_margin(
                    g_x,
                    g,
                    r,
                )
                if u is None:
                    continue

                kappa = a2.solve_kappa(
                    theta_earth,
                    selected_f,
                    g_x,
                    g,
                    u,
                    r,
                )
                if kappa is None or kappa > a2.MAX_KAPPA:
                    continue

                masses = np.sqrt(
                    np.linalg.eigvalsh(
                        a2.physical_mass2(
                            0.0,
                            g_x,
                            g,
                            u,
                            r,
                        )
                    )
                )

                point = {
                    "g_x": g_x,
                    "g": g,
                    "r": r,
                    "u": float(u),
                    "v": float(u * r),
                    "kappa": float(kappa),
                    "min_mass": float(masses[0]),
                    "max_mass": float(masses[-1]),
                    "mass_ratio": float(masses[-1] / masses[0]),
                }

                ratio_probe = high_precision_ratio(
                    a2,
                    EPS_PROBE,
                    point,
                    selected_f,
                )

                if (
                    not math.isfinite(ratio_probe)
                    or ratio_probe <= 0.0
                ):
                    continue

                epsilon_allowed_est = EPS_PROBE / ratio_probe

                floor_one, _, _, denom_one = optimized_rg_floor(
                    g,
                    DELTA_B_ONE_WEYL,
                    point["mass_ratio"],
                )

                floor_three, _, _, denom_three = optimized_rg_floor(
                    g,
                    DELTA_B_THREE_NEUTRINOS,
                    point["mass_ratio"],
                )

                point.update(
                    {
                        "ratio_probe": ratio_probe,
                        "epsilon_allowed_est": epsilon_allowed_est,
                        "floor_one_est": floor_one,
                        "floor_three_est": floor_three,
                        "deficit_one_est": floor_one / epsilon_allowed_est,
                        "deficit_three_est": floor_three / epsilon_allowed_est,
                        "denom_one": denom_one,
                        "denom_three": denom_three,
                    }
                )

                candidates.append(point)

    return candidates


