def require_marker(path: Path, marker: str) -> None:
    """Require an exact upstream scientific marker."""

    if not path.exists():
        raise RuntimeError(f"Missing upstream log: {path}")

    text = path.read_text(errors="replace")
    if marker not in text:
        raise RuntimeError(
            f"Missing required marker in {path.name}: {marker}"
        )


def exact_scalar(path: Path, prefix: str) -> float:
    """Read one scalar from an exact executed-log prefix."""

    pattern = re.compile(
        rf"^{re.escape(prefix)}([+\-0-9.eE]+)$",
        re.MULTILINE,
    )
    match = pattern.search(path.read_text(errors="replace"))
    if match is None:
        raise RuntimeError(
            f"Could not find {prefix!r} in {path.name}"
        )
    value = float(match.group(1))
    if not math.isfinite(value):
        raise RuntimeError(
            f"Nonfinite scalar for {prefix!r} in {path.name}"
        )
    return value


def sha256(path: Path) -> str:
    """Return SHA-256 for one scientific source file."""

    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_module(name: str, path: Path):
    """Import a repository simulation without invoking its main()."""

    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot import {path}")

    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module

    try:
        spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(name, None)
        raise

    return module


def charge_square_sum(fields, which: str) -> Fraction:
    """Return exact sum of Weyl charge squares including multiplicities."""

    total = Fraction(0)

    for field in fields:
        charge = (
            field.baryon
            if which == "B"
            else field.lepton
        )
        multiplicity = (
            field.generations
            * field.color_dim
            * field.su2_dim
        )
        total += multiplicity * charge * charge

    return total


def fermion_beta_coefficient(charge_square: Fraction) -> Fraction:
    """Return exact one-loop U(1) Weyl-fermion beta coefficient."""

    return Fraction(2, 3) * charge_square


def epsilon_from_couplings(g_b: float, g_l: float) -> float:
    """Return the 020A2 exchange-breaking parameter epsilon."""

    return (g_b - g_l) / (g_b + g_l)


def optimized_rg_floor(
    g_b: float,
    delta_b: float,
    mass_ratio: float,
) -> tuple[float, float, float, float]:
    """Return the exact one-loop minimax differential-running floor.

    We retain only the differential beta-function contribution delta_b and
    deliberately set the baryonic contribution to zero.

    The normalization of g_L is optimized so that endpoint epsilon values are
    equal and opposite.

    Returns:
        floor,
        g_l_low,
        g_l_high,
        denominator_high
    """

    if g_b <= 0.0:
        raise ValueError("g_b must be positive")
    if delta_b <= 0.0:
        raise ValueError("delta_b must be positive")
    if mass_ratio <= 1.0:
        raise ValueError("mass_ratio must exceed one")

    k = (
        delta_b
        / (8.0 * math.pi**2)
        * math.log(mass_ratio)
    )

    # Let y = g_L(low)^2.
    # Minimax condition:
    #
    #     g_L(low) * g_L(high) = g_B^2
    #
    # together with
    #
    #     g_L(high)^2 = y / (1 - k y)
    #
    # gives
    #
    #     y^2 + k g_B^4 y - g_B^4 = 0.
    #
    g4 = g_b**4
    discriminant = k * k * g4 * g4 + 4.0 * g4

    y = (
        -k * g4
        + math.sqrt(discriminant)
    ) / 2.0

    if y <= 0.0:
        raise RuntimeError("Invalid minimax low-scale coupling")

    denominator = 1.0 - k * y
    if denominator <= 0.0:
        raise RuntimeError(
            "One-loop U(1) running hits a Landau singularity "
            "inside the tested vector spectrum"
        )

    g_l_low = math.sqrt(y)
    g_l_high = math.sqrt(y / denominator)

    eps_low = epsilon_from_couplings(g_b, g_l_low)
    eps_high = epsilon_from_couplings(g_b, g_l_high)

    floor = max(abs(eps_low), abs(eps_high))

    return floor, g_l_low, g_l_high, denominator


def brute_force_rg_floor(
    g_b: float,
    delta_b: float,
    mass_ratio: float,
) -> float:
    """Independent numerical minimization of the endpoint RG mismatch."""

    k = (
        delta_b
        / (8.0 * math.pi**2)
        * math.log(mass_ratio)
    )

    def objective(g_l_low: float) -> float:
        denominator = 1.0 - k * g_l_low * g_l_low
        if denominator <= 0.0:
            return 1.0e6

        g_l_high = g_l_low / math.sqrt(denominator)

        return max(
            abs(epsilon_from_couplings(g_b, g_l_low)),
            abs(epsilon_from_couplings(g_b, g_l_high)),
        )

    result = minimize_scalar(
        objective,
        bounds=(0.25 * g_b, 1.75 * g_b),
        method="bounded",
        options={
            "xatol": 1.0e-14,
            "maxiter": 1000,
        },
    )

    if not result.success:
        raise RuntimeError("Brute-force RG minimization failed")

    return float(result.fun)


