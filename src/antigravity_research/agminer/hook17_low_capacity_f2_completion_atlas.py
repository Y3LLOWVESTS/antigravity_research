def _source_is_closed(
    row: dict[str, Any],
) -> bool:
    """Return whether a source row is permanently unavailable in this atlas."""

    return (
        row[
            "current_status"
        ].startswith(
            "CLOSED_"
        )
        or
        row[
            "current_status"
        ].startswith(
            "NOT_AUTHORIZED_"
        )
    )


def _shape_bonus(
    source: dict[str, Any],
) -> int:
    """Return deterministic priority bonus for A12C profile compatibility."""

    status = source[
        "source_shape_reference_compatibility"
    ]

    if status == "EXACT":
        return 15

    if status in {
        "PLAUSIBLE_NOT_CERTIFIED",
        "CAN_TARGET_REFERENCE_PROFILE",
        "CURRENT_PROFILE_ENGINEERABLE_IN_PRINCIPLE",
    }:
        return 5

    return 0


def _conservation_bonus(
    source: dict[str, Any],
) -> int:
    """Return deterministic bonus for exact source conservation."""

    status = source[
        "exact_conservation"
    ]

    if status.startswith(
        "YES"
    ):
        return 10

    return 0


@lru_cache(maxsize=1)
def completion_combination_atlas() -> list[
    dict[str, Any]
]:
    """Cross source families with allowed field-sector metric portals."""

    sources = (
        source_completion_atlas()
    )

    portals = (
        field_sector_portal_atlas()
    )

    rows = []

    for source in sources:
        supported = set(
            source[
                "supported_sectors"
            ]
        )

        for portal in portals:
            if (
                portal[
                    "field_sector"
                ]
                not in supported
            ):
                continue

            source_closed = (
                _source_is_closed(
                    source
                )
            )

            portal_closed = bool(
                portal[
                    "structurally_closed"
                ]
            )

            if source_closed:
                status = (
                    "SOURCE_CLOSED_OR_POLICY_EXCLUDED"
                )

            elif portal_closed:
                status = (
                    "METRIC_STRUCTURE_STRUCTURALLY_CLOSED_IN_SECTOR"
                )

            else:
                status = (
                    "OPEN_PRE_BVP"
                )

            exact_kernel_reuse = bool(
                portal[
                    "reference_kernel_reuse"
                ]
                and
                source[
                    "source_shape_reference_compatibility"
                ]
                ==
                "EXACT"
            )

            conditional_kernel_reuse = bool(
                portal[
                    "reference_kernel_reuse"
                ]
                and
                source[
                    "source_shape_reference_compatibility"
                ]
                in {
                    "PLAUSIBLE_NOT_CERTIFIED",
                    "CAN_TARGET_REFERENCE_PROFILE",
                    "CURRENT_PROFILE_ENGINEERABLE_IN_PRINCIPLE",
                }
            )

            score = int(
                source[
                    "priority_base"
                ]
            )

            score += (
                25
                if exact_kernel_reuse
                else 0
            )

            score += (
                10
                if conditional_kernel_reuse
                else 0
            )

            score += (
                _shape_bonus(
                    source
                )
            )

            score += (
                _conservation_bonus(
                    source
                )
            )

            if (
                not portal[
                    "reference_kernel_reuse"
                ]
                and
                not portal_closed
            ):
                score -= 10

            if status != "OPEN_PRE_BVP":
                score = 0

            rows.append(
                {
                    "source_id":
                        source[
                            "source_id"
                        ],

                    "portal_id":
                        portal[
                            "portal_id"
                        ],

                    "field_sector":
                        portal[
                            "field_sector"
                        ],

                    "metric_structure":
                        portal[
                            "metric_structure"
                        ],

                    "status":
                        status,

                    "exact_a12c_kernel_reuse":
                        exact_kernel_reuse,

                    "conditional_a12c_kernel_reuse":
                        conditional_kernel_reuse,

                    "priority_score_not_probability":
                        score,

                    "source_next_gate":
                        source[
                            "next_gate"
                        ],

                    "complete_energy_certified":
                        False,
                }
            )

    rows.sort(
        key=lambda row: (
            -int(
                row[
                    "priority_score_not_probability"
                ]
            ),
            row[
                "source_id"
            ],
            row[
                "portal_id"
            ],
        )
    )

    return rows


@lru_cache(maxsize=1)
def open_completion_rerank() -> list[
    dict[str, Any]
]:
    """Return only structurally open, policy-authorized completion rows."""

    return [
        row
        for row in completion_combination_atlas()
        if row[
            "status"
        ]
        ==
        "OPEN_PRE_BVP"
    ]


