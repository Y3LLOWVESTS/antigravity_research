def _epsilon4(
    indices: tuple[
        int,
        int,
        int,
        int,
    ],
) -> int:
    """Return epsilon^{0123}=+1 convention."""

    if len(
        set(
            indices
        )
    ) != 4:
        return 0

    inversions = sum(
        indices[
            i
        ]
        >
        indices[
            j
        ]
        for i in range(
            4
        )
        for j in range(
            i + 1,
            4,
        )
    )

    return (
        -1
        if inversions % 2
        else 1
    )


